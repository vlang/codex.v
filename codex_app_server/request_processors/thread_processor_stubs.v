// STUB: request_processors/thread_enrichment.rs enriches list results from loaded core threads.
// The concrete generic Rust callback is represented by this V overload for `[]Thread`.
pub fn enrich_loaded_thread_summaries(manager &ThreadManager, watch_manager &ThreadWatchManager, mut threads []codex_app_server_protocol.Thread) {
	mut thread_ids := []string{cap: threads.len}
	for thread_value in threads {
		thread_ids << thread_value.id.clone()
	}
	statuses := watch_manager.loaded_statuses_for_threads(thread_ids)
	for mut thread_value in threads {
		watched_status := statuses[thread_value.id] or { codex_app_server_protocol.ThreadStatus{} }
		has_watched_status := thread_value.id in statuses
		if has_watched_status {
			thread_value.status = watched_status
		}
		if has_watched_status && watched_status.kind == .not_loaded {
			continue
		}
		thread_id := codex_protocol.thread_id_from_string(&thread_value.id) or { continue }
		loaded_thread := manager.get_thread(&thread_id) or { continue }
		config_snapshot := loaded_thread.config_snapshot()
		apply_live_thread_settings(mut thread_value, &config_snapshot)
		if thread_value.source.source_kind != .sub_agent
			|| (thread_value.source.sub_agent or { codex_protocol.SubAgentSource{} }).source_kind != .thread_spawn {
			continue
		}
		match loaded_thread.agent_status() {
			.running {
				if !has_watched_status {
					thread_value.status = resolve_thread_status(codex_app_server_protocol.ThreadStatus{
						kind: .idle
					}, true)
				}
			}
			.pending_init, .interrupted, .completed {
				if !has_watched_status {
					thread_value.status = codex_app_server_protocol.ThreadStatus{ kind: .idle }
				}
			}
			.errored {
				thread_value.status = codex_app_server_protocol.ThreadStatus{ kind: .system_error }
			}
			.shutdown, .not_found {
				thread_value.status = codex_app_server_protocol.ThreadStatus{ kind: .not_loaded }
				continue
			}
		}
		thread_value.can_accept_direct_input = can_accept_direct_input(loaded_thread.multi_agent_version(), &config_snapshot.session_source)
	}
}

// STUB: request_processors/thread_enrichment.rs enriches search results from loaded core threads.
pub fn enrich_loaded_thread_search_results(manager &ThreadManager, watch_manager &ThreadWatchManager, mut results []codex_app_server_protocol.ThreadSearchResult) {
	mut threads := []codex_app_server_protocol.Thread{cap: results.len}
	for result in results {
		threads << clone_api_thread(&result.thread)
	}
	enrich_loaded_thread_summaries(manager, watch_manager, mut threads)
	for index, thread_value in threads {
		results[index].thread = thread_value
	}
}

// STUB: request_processors.rs applies fields whose authoritative value comes from the live
// configuration rather than persisted thread metadata.
pub fn apply_live_thread_settings(mut thread_value codex_app_server_protocol.Thread, snapshot &ThreadConfigSnapshot) {
	thread_value.model = snapshot.model.clone()
	thread_value.reasoning_effort = snapshot.reasoning_effort
	selections := snapshot.environment_selections()
	mut environments := []codex_app_server_protocol.ThreadEnvironment{cap: selections.len}
	for selection in selections {
		environments << codex_app_server_protocol.ThreadEnvironment{
			environment_id:          selection.environment_id.clone()
			cwd:                     selection.cwd.path.clone()
			runtime_workspace_roots: selection.workspace_roots.map(it.path.clone())
		}
	}
	thread_value.environments = codex_app_server_protocol.OptionalThreadEnvironments{
		has_value: true
		value:     environments
	}
}

