// STUB: OptionalTurnEnvironmentSelections adapts the Result<Option<Vec<_>>> returned by
// request_processors.rs without collapsing omitted and explicitly empty environment lists.
pub struct OptionalTurnEnvironmentSelections {
pub:
	has_value bool
	value     []codex_protocol.TurnEnvironmentSelection
}

// STUB: resolve_turn_environment_selections is owned by app-server/request_processors.rs.
pub fn resolve_turn_environment_selections(thread_manager &ThreadManager, environments ?[]codex_app_server_protocol.TurnEnvironmentParams) !OptionalTurnEnvironmentSelections {
	values := environments or { return OptionalTurnEnvironmentSelections{} }
	mut selections := []codex_protocol.TurnEnvironmentSelection{cap: values.len}
	for environment in values {
		if !is_inferred_absolute_path(&environment.cwd) {
			return fail(invalid_request('invalid cwd for environment `${environment.environment_id}`: path `${environment.cwd}` does not use absolute POSIX or Windows path syntax'))
		}
		cwd := codex_protocol.PathUri{ path: environment.cwd.clone() }
		mut workspace_roots := []codex_protocol.PathUri{}
		if roots := environment.runtime_workspace_roots {
			for root in roots {
				if !is_inferred_absolute_path(&root) {
					return fail(invalid_request('invalid runtime workspace root for environment `${environment.environment_id}`: path `${root}` does not use absolute POSIX or Windows path syntax'))
				}
				mut duplicate := false
				for existing in workspace_roots {
					if existing.path == root {
						duplicate = true
						break
					}
				}
				if !duplicate {
					workspace_roots << codex_protocol.PathUri{ path: root.clone() }
				}
			}
		} else {
			workspace_roots << codex_protocol.PathUri{ path: environment.cwd.clone() }
		}
		selections << codex_protocol.TurnEnvironmentSelection{
			environment_id:  environment.environment_id.clone()
			cwd:             cwd
			workspace_roots: workspace_roots
			config:          codex_protocol.EnvironmentConfigState{}
		}
	}
	thread_manager.validate_environment_selections(&selections) or {
		return fail(invalid_request(err.msg()))
	}
	return OptionalTurnEnvironmentSelections{ has_value: true, value: selections }
}

// STUB: resolve_runtime_workspace_roots is owned by app-server/request_processors.rs.
pub fn resolve_runtime_workspace_roots(workspace_roots []string) []string {
	mut resolved := []string{}
	for root in workspace_roots {
		normalized := os.norm_path(root)
		if normalized !in resolved {
			resolved << normalized
		}
	}
	return resolved
}

// STUB: validates the absolute path forms accepted by LegacyAppPathString inference.
fn is_inferred_absolute_path(path &string) bool {
	value := *path
	if os.is_abs_path(value.clone()) {
		return true
	}
	return value.len >= 3 && value[1] == `:` && (value[2] == `\\` || value[2] == `/`)
}

