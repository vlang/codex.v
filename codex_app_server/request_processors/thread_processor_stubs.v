// STUB: with_thread_spawn_agent_metadata is owned by
// app-server/request_processors/thread_summary.rs.
pub fn with_thread_spawn_agent_metadata(source codex_protocol.SessionSource, agent_nickname ?string, agent_role ?string) codex_protocol.SessionSource {
	if agent_nickname == none && agent_role == none {
		return source
	}
	if source.source_kind != .sub_agent {
		return source
	}
	// V cannot safely partially move an optional payload and then drop the enclosing owned struct;
	// make Rust's by-value match reconstruction explicit at this boundary.
	cloned_source := codex_protocol.clone_session_source(&source)
	subagent := cloned_source.sub_agent or {
		return codex_protocol.SessionSource{ source_kind: .sub_agent }
	}
	if subagent.source_kind != .thread_spawn {
		return codex_protocol.SessionSource{
			source_kind: .sub_agent
			sub_agent:   subagent
		}
	}
	resolved_nickname := if nickname := agent_nickname {
		?string(nickname)
	} else {
		subagent.agent_nickname
	}
	resolved_role := if role := agent_role { ?string(role) } else { subagent.agent_role }
	return codex_protocol.SessionSource{
		source_kind: .sub_agent
		sub_agent:   codex_protocol.SubAgentSource{
			source_kind:      subagent.source_kind
			parent_thread_id: subagent.parent_thread_id
			depth:            subagent.depth
			agent_path:       subagent.agent_path
			agent_nickname:   resolved_nickname
			agent_role:       resolved_role
			other:            subagent.other
		}
	}
}

